import type { Metadata } from "next";

export const SITE_NAME = "Mi Amor Tales";
export const SITE_URL = "https://www.miamortales.com";
export const DEFAULT_TITLE = "Jaipur Wedding Photographer & Films | Mi Amor Tales";
export const DEFAULT_DESCRIPTION =
  "Mi Amor Tales creates documentary wedding photography and cinematic films in Jaipur and across India, preserving honest moments with an editorial eye.";

export function absoluteUrl(path = "/") {
  return new URL(path, SITE_URL).toString();
}

export function pageMetadata({
  title,
  description,
  path,
}: {
  title: string;
  description: string;
  path: string;
}): Metadata {
  return {
    title,
    description,
    alternates: { canonical: path },
    openGraph: {
      type: "website",
      locale: "en_IN",
      url: path,
      siteName: SITE_NAME,
      title,
      description,
    },
    twitter: {
      card: "summary_large_image",
      title,
      description,
    },
  };
}

